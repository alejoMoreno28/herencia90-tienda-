begin;

create table if not exists public.socios (
    id smallint primary key,
    nombre text not null,
    porcentaje numeric(5,2) not null default 50.00,
    activo boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    constraint socios_id_check check (id in (1, 2)),
    constraint socios_nombre_check check (char_length(btrim(nombre)) between 1 and 80),
    constraint socios_porcentaje_check check (porcentaje = 50.00)
);

create table if not exists public.cortes_ganancias (
    id bigint generated by default as identity primary key,
    fecha date not null default current_date,
    caja_fisica_snapshot numeric not null check (caja_fisica_snapshot >= 0),
    retiros_efectivo_snapshot numeric not null check (retiros_efectivo_snapshot >= 0),
    caja_antes_socios_snapshot numeric not null check (caja_antes_socios_snapshot >= 0),
    deuda_tarjeta_snapshot numeric not null check (deuda_tarjeta_snapshot >= 0),
    base_repartible_snapshot numeric not null check (base_repartible_snapshot >= 0),
    cortes_previos_snapshot numeric not null check (cortes_previos_snapshot >= 0),
    maximo_nuevo_corte_snapshot numeric not null check (maximo_nuevo_corte_snapshot >= 0),
    monto_aprobado numeric not null check (
        monto_aprobado > 0
        and trunc(monto_aprobado) = monto_aprobado
        and mod(monto_aprobado, 2) = 0
    ),
    monto_socio_1 numeric not null check (monto_socio_1 >= 0),
    monto_socio_2 numeric not null check (monto_socio_2 >= 0),
    estado text not null default 'activo' check (estado in ('activo', 'anulado')),
    nota text not null default '',
    created_by uuid,
    created_at timestamptz not null default now(),
    anulado_at timestamptz,
    motivo_anulacion text,
    constraint cortes_ganancias_partes_check check (
        monto_socio_1 = monto_socio_2
        and monto_socio_1 + monto_socio_2 = monto_aprobado
    )
);

create table if not exists public.movimientos_socios (
    id bigint generated by default as identity primary key,
    corte_id bigint not null references public.cortes_ganancias(id),
    socio_id smallint not null references public.socios(id),
    tipo text not null check (tipo in ('retiro_efectivo', 'retiro_producto', 'reversion')),
    fecha date not null default current_date,
    valor_participacion_cop numeric not null,
    efecto_caja_cop numeric not null default 0,
    producto_id integer references public.productos(id),
    talla text,
    cantidad integer,
    costo_unitario_usd numeric,
    trm_snapshot numeric,
    costo_unitario_cop numeric,
    valor_comercial_unitario_cop numeric,
    revision_tributaria text not null default 'no_aplica'
        check (revision_tributaria in ('pendiente', 'revisado', 'no_aplica')),
    movimiento_revertido_id bigint references public.movimientos_socios(id),
    transaccion_origen_id bigint references public.transacciones(id),
    estado text not null default 'activo' check (estado in ('activo', 'revertido')),
    nota text not null default '',
    created_by uuid,
    created_at timestamptz not null default now(),
    constraint movimientos_socios_cantidad_check check (cantidad is null or cantidad > 0),
    constraint movimientos_socios_producto_check check (
        tipo <> 'retiro_producto'
        or (
            valor_participacion_cop > 0
            and efecto_caja_cop = 0
            and cantidad is not null
            and revision_tributaria in ('pendiente', 'revisado', 'no_aplica')
        )
    ),
    constraint movimientos_socios_efectivo_check check (
        tipo <> 'retiro_efectivo'
        or (
            valor_participacion_cop > 0
            and efecto_caja_cop = valor_participacion_cop
            and revision_tributaria = 'no_aplica'
        )
    ),
    constraint movimientos_socios_reversion_check check (
        tipo <> 'reversion'
        or (
            valor_participacion_cop < 0
            and movimiento_revertido_id is not null
            and revision_tributaria = 'no_aplica'
        )
    )
);

create unique index if not exists movimientos_socios_reversion_unica
    on public.movimientos_socios (movimiento_revertido_id)
    where movimiento_revertido_id is not null;

create unique index if not exists movimientos_socios_transaccion_origen_unica
    on public.movimientos_socios (transaccion_origen_id)
    where transaccion_origen_id is not null;

create index if not exists movimientos_socios_corte_idx
    on public.movimientos_socios (corte_id, fecha desc);

create index if not exists movimientos_socios_socio_idx
    on public.movimientos_socios (socio_id, fecha desc);

